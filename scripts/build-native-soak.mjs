import {build} from 'vite';
import {cp,mkdir,rm,access,writeFile} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

// Separate debug-only web assets. The normal web/release build excludes tests.
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const output=path.join(root,'android/app/build/native-soak-web');
const debugAssets=path.join(root,'android/app/src/debug/assets/public');
const marker=path.join(debugAssets,'.maras-soak-generated');
let exists=false;try{await access(debugAssets);exists=true;}catch{}
if(exists){
  try{await access(marker);}catch{throw new Error('Refusing to replace unmarked debug assets: '+debugAssets);}
  await rm(debugAssets,{recursive:true,force:true});
}
if(process.argv.includes('--clean')){console.log('Normal APK: diagnostic overlay cleared.');process.exit(0);}
const encounters=process.argv.includes('--encounters');
await build({root,configFile:false,base:'./',build:{outDir:output,emptyOutDir:true,chunkSizeWarningLimit:800,rollupOptions:{input:path.join(root,encounters?'tests/encounter-audit-preview.html':'tests/mobile-soak-preview.html')}}});
await mkdir(debugAssets,{recursive:true});await cp(output,debugAssets,{recursive:true});if(encounters)await cp(path.join(output,'tests/encounter-audit-preview.html'),path.join(debugAssets,'tests/mobile-soak-preview.html'));
await writeFile(marker,'Generated by scripts/build-native-soak.mjs\n');
console.log('Diagnostic assets ready; remove android/app/src/debug/assets/public before the normal APK build.');
